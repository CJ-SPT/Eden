"""Enforce EditorConfig's line limit where formatters cannot guarantee it."""
import argparse
import json
from pathlib import Path, PurePosixPath
import subprocess
import sys


EXCEPTIONS_PATH = "tools/formatting-exceptions.json"
EXCLUDED_DIRECTORIES = {".git", "artifacts", "bin", "obj", "TestResults"}
PROJECT_EXTENSIONS = {".cs", ".csproj", ".props", ".targets", ".slnx"}


def is_covered(path):
    file = PurePosixPath(path)
    if EXCLUDED_DIRECTORIES.intersection(file.parts):
        return False
    if file.name.endswith((".g.cs", ".generated.cs")):
        return False
    if file.suffix in PROJECT_EXTENSIONS:
        return True
    if file.suffix != ".json":
        return False
    return (
        path == "global.json"
        or file.parts[0] in {".config", ".vscode"}
        or file.name == "launchSettings.json"
        or file.match("appsettings*.json")
    )


def line_limit(root):
    # EditorConfig is the single source of truth for the C# width.
    in_csharp = False
    for line in (root / ".editorconfig").read_text(encoding="utf-8-sig").splitlines():
        line = line.strip()
        if line.startswith("["):
            in_csharp = line == "[*.cs]"
        elif in_csharp and line.startswith("max_line_length"):
            limit = int(line.split("=", 1)[1].strip())
            if limit > 0:
                return limit
    raise ValueError(".editorconfig must set a positive max_line_length in [*.cs].")


def check_width(root, paths, exceptions, limit):
    problems = []
    allowed = set()
    for index, entry in enumerate(exceptions):
        label = f"{EXCEPTIONS_PATH}: entry {index + 1}"
        if not isinstance(entry, dict) or set(entry) != {"path", "line", "reason"}:
            problems.append(f"{label}: expected path, line and reason.")
            continue
        path, line, reason = entry["path"], entry["line"], entry["reason"]
        if not all(isinstance(value, str) and value.strip() for value in (path, line, reason)):
            problems.append(f"{label}: path, line and reason must be nonempty strings.")
            continue
        file = PurePosixPath(path)
        if "\\" in path or file.is_absolute() or ".." in file.parts or file.as_posix() != path:
            problems.append(f"{label}: use a normalized repository-relative path with forward slashes.")
            continue
        key = (path, line)
        if key in allowed:
            problems.append(f"{label}: duplicate exception for {path}.")
        allowed.add(key)

    used = set()
    for path in sorted(set(paths)):
        file = root / path
        if not is_covered(path) or not file.is_file():
            continue
        lines = file.read_text(encoding="utf-8-sig").splitlines()
        if file.suffix == ".cs" and any(
            "<auto-generated" in line or "<autogenerated" in line for line in lines[:2]
        ):
            continue
        for number, line in enumerate(lines, 1):
            # Tabs occupy four display columns in C#; other covered files use two.
            width = len(line.expandtabs(4 if file.suffix == ".cs" else 2))
            if width <= limit:
                continue
            key = (path, line)
            if key in allowed:
                used.add(key)
            else:
                problems.append(f"{path}:{number}: line is {width} characters; maximum is {limit}.")

    for path, _ in sorted(allowed - used):
        problems.append(f"{EXCEPTIONS_PATH}: unused exception for {path}; remove or update it.")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        paths = subprocess.check_output(
            ["git", "-C", str(root), "ls-files", "--cached", "--others", "--exclude-standard", "-z"]
        ).decode("utf-8").split("\0")
        exceptions = json.loads((root / EXCEPTIONS_PATH).read_text(encoding="utf-8-sig"))
        if not isinstance(exceptions, list):
            raise ValueError(f"{EXCEPTIONS_PATH} must contain a JSON array.")
        limit = line_limit(root)
        problems = check_width(root, filter(None, paths), exceptions, limit)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"Formatting check failed: {error}", file=sys.stderr)
        return 1
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    print(f"Line-width check passed (maximum {limit}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
