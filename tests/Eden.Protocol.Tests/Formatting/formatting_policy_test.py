"""Focused tests for the strict width policy; no third-party Python packages."""
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "tools"))
from check_formatting import check_width, is_covered, line_limit


class FormattingPolicyTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)

    def write(self, path, text):
        file = self.root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text + "\n", encoding="utf-8")
        return path

    def test_width_boundary(self):
        for width in (140, 141):
            with self.subTest(width=width):
                path = self.write("Sample.cs", "x" * width)
                problems = check_width(self.root, [path], [], 140)
                self.assertEqual(width > 140, bool(problems))

    def test_valid_exception_and_required_reason(self):
        line = "x" * 141
        path = self.write("Sample.cs", line)
        entry = {"path": path, "line": line, "reason": "Indivisible fixture content."}
        self.assertEqual([], check_width(self.root, [path], [entry], 140))
        entry["reason"] = " "
        self.assertTrue(check_width(self.root, [path], [entry], 140))

    def test_unused_and_duplicate_exceptions(self):
        path = self.write("Sample.cs", "x" * 141)
        entry = {"path": path, "line": "x" * 141, "reason": "Fixture."}
        self.assertTrue(any("duplicate" in p for p in check_width(self.root, [path], [entry, entry], 140)))
        self.write(path, "short")
        self.assertTrue(any("unused" in p for p in check_width(self.root, [path], [entry], 140)))
        self.assertTrue(any("unused" in p for p in check_width(self.root, [], [entry], 140)))

    def test_exception_matches_exact_path_and_content(self):
        path = self.write("Sample.cs", "x" * 141)
        entry = {"path": "Other.cs", "line": "x" * 141, "reason": "Fixture."}
        self.assertEqual(2, len(check_width(self.root, [path], [entry], 140)))
        entry.update(path=path, line="y" * 141)
        self.assertEqual(2, len(check_width(self.root, [path], [entry], 140)))

    def test_malformed_exceptions_and_nonrelative_paths_are_rejected(self):
        entries = [None, {}, {"path": "Sample.cs", "line": "x" * 141}]
        entries.extend(
            {"path": path, "line": "x" * 141, "reason": "Fixture."}
            for path in ("../Sample.cs", "/Sample.cs", "./Sample.cs", "src\\Sample.cs")
        )
        for entry in entries:
            with self.subTest(entry=entry):
                self.assertTrue(check_width(self.root, [], [entry], 140))

    def test_generated_and_build_outputs_are_excluded(self):
        paths = [self.write(path, "x" * 141) for path in (
            "src/CatalogData.g.cs", "src/Model.generated.cs", "src/obj/Generated.cs",
            "artifacts/Sample.cs", "src/bin/Sample.cs", "src/TestResults/Sample.cs",
        )]
        paths.append(self.write("src/Generated.cs", "// <auto-generated>\n" + "x" * 141))
        self.assertEqual([], check_width(self.root, paths, [], 140))

    def test_configuration_is_covered_but_data_and_documents_are_not(self):
        for path in (
            "Eden.slnx", "Directory.Build.props", "Build.targets", "src/App.csproj", "global.json",
            ".config/dotnet-tools.json", ".vscode/settings.json", "src/appsettings.Development.json",
            "src/Properties/launchSettings.json",
        ):
            with self.subTest(path=path):
                self.assertTrue(is_covered(path))
                self.write(path, "x" * 141)
                self.assertTrue(check_width(self.root, [path], [], 140))
        for path in (
            "README.md", "tools/DevelopmentClient.ps1", "tools/catalog/build.py",
            "src/Persistence/starter-market.json", "tools/catalog/build-3662168.json",
            "tools/formatting-exceptions.json",
        ):
            self.assertFalse(is_covered(path))

    def test_tabs_count_display_columns(self):
        path = self.write("Sample.cs", "\t" + "x" * 137)
        self.assertTrue(check_width(self.root, [path], [], 140))

    def test_width_comes_from_editorconfig(self):
        self.write(".editorconfig", "[*.cs]\nmax_line_length = 140\n[*.json]\nmax_line_length = 80")
        self.assertEqual(140, line_limit(self.root))
        self.write(".editorconfig", "[*.cs]\nmax_line_length = 0")
        with self.assertRaises(ValueError):
            line_limit(self.root)


if __name__ == "__main__":
    unittest.main()
