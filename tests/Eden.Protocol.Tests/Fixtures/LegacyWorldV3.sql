CREATE TABLE station (
    id INTEGER PRIMARY KEY, type INTEGER NOT NULL, owner INTEGER NOT NULL, system INTEGER NOT NULL,
    constellation INTEGER NOT NULL, region INTEGER NOT NULL, operation INTEGER NOT NULL, orbit INTEGER NOT NULL,
    x REAL NOT NULL, y REAL NOT NULL, z REAL NOT NULL);
CREATE TABLE ship_type (id INTEGER PRIMARY KEY, group_id INTEGER NOT NULL, category INTEGER NOT NULL, capacity REAL NOT NULL, turrets INTEGER NOT NULL);
CREATE TABLE account (id INTEGER PRIMARY KEY);
CREATE TABLE pilot (id INTEGER PRIMARY KEY, account INTEGER NOT NULL UNIQUE REFERENCES account(id),
    name TEXT NOT NULL, corporation INTEGER NOT NULL, active_ship INTEGER NOT NULL,
    FOREIGN KEY (active_ship, id) REFERENCES ship(id, owner) DEFERRABLE INITIALLY DEFERRED);
-- Each ship row is one assembled item. Docked location is owned by the ship.
CREATE TABLE ship (id INTEGER PRIMARY KEY, owner INTEGER NOT NULL REFERENCES pilot(id),
    type INTEGER NOT NULL REFERENCES ship_type(id), station INTEGER NOT NULL REFERENCES station(id), name TEXT NOT NULL, UNIQUE(id,owner));
